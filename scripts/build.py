#!/usr/bin/env python3
"""Generate Surge RULE-SET files from one MetaCubeX revision."""

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import ipaddress
import json
from pathlib import Path
import re
from urllib.parse import quote
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parent.parent
DOMAIN = re.compile(r"[a-z0-9_-]+(?:\.[a-z0-9_-]+)*")


def fetch(url):
    request = Request(url, headers={"User-Agent": "SubBoost-Surge-Rules"})
    with urlopen(request, timeout=45) as response:
        return response.read()


def resolve_revision(upstream):
    url = "https://api.github.com/repos/{}/branches/{}".format(
        upstream["repository"], quote(upstream["branch"], safe="")
    )
    return json.loads(fetch(url))["commit"]["sha"]


def source_url(upstream, revision, source):
    return "https://raw.githubusercontent.com/{}/{}/{}/{}".format(
        upstream["repository"], revision, upstream["directory"], quote(source, safe="/")
    )


def convert_source(source, data):
    rules = set()
    for number, raw in enumerate(data.decode("utf-8").splitlines(), 1):
        value = raw.strip()
        if not value or value.startswith("#"):
            continue
        if source.startswith("geosite/"):
            suffix = value.startswith("+.")
            hostname = (value[2:] if suffix else value).encode("idna").decode("ascii").lower()
            if not DOMAIN.fullmatch(hostname) or len(hostname) > 253 or any(
                len(label) > 63 for label in hostname.split(".")
            ):
                raise ValueError("{}:{}: unsupported domain {!r}".format(source, number, value))
            rules.add("{},{}".format("DOMAIN-SUFFIX" if suffix else "DOMAIN", hostname))
        elif source.startswith("geoip/"):
            network = ipaddress.ip_network(value)
            kind = "IP-CIDR" if network.version == 4 else "IP-CIDR6"
            rules.add("{},{},no-resolve".format(kind, network))
        else:
            raise ValueError("Unsupported source: " + source)
    if not rules:
        raise ValueError("Empty source: " + source)
    return rules


def make_artifacts(catalog, revision, sources):
    converted = {source: convert_source(source, data) for source, data in sources.items()}
    artifacts = {}
    entries = []
    report = []
    for group in catalog["groups"]:
        for prefix, suffix in (("geosite/", ""), ("geoip/", "-ip")):
            paths = [source for source in group["sources"] if source.startswith(prefix)]
            if not paths:
                continue
            name = group["id"] + suffix + ".list"
            rules = sorted(set().union(*(converted[source] for source in paths)))
            header = [
                "# " + group["name"] + (" IP" if suffix else ""),
                "# Source: " + catalog["upstream"]["repository"],
                "# Entries: " + str(len(rules)),
            ] + ["# " + path for path in paths]
            content = "\n".join(header + rules) + "\n"
            artifacts["rules/" + name] = content
            entry = dict(group=group["id"], file=name, policy=group["policy"], ip=bool(suffix))
            entries.append(entry)
            report.append(dict(
                file=name,
                group=group["id"],
                sources=paths,
                entries=len(rules),
                sha256=hashlib.sha256(content.encode("utf-8")).hexdigest(),
            ))

    # The catalogue orders domain rules. All IP rules follow the domain phase;
    # private IPs lead the IP phase, and domestic IPs come after service IPs.
    ordered = [entry for entry in entries if not entry["ip"]]
    ordered += [entry for entry in entries if entry["ip"] and entry["group"] == "private"]
    ordered += [entry for entry in entries if entry["ip"] and entry["group"] not in ("private", "cn")]
    ordered += [entry for entry in entries if entry["ip"] and entry["group"] == "cn"]
    references = [
        "# Generated by scripts/build.py; edit catalog.json instead.",
        "# Merge into the existing [Rule] section, before its FINAL rule.",
        "[Rule]",
    ]
    references += [
        "RULE-SET,{}/{},{}".format(catalog["publish_url"], entry["file"], entry["policy"])
        for entry in ordered
    ]
    references.append("FINAL," + catalog["final_policy"])
    artifacts["examples/rules.conf"] = "\n".join(references) + "\n"

    policies = list(dict.fromkeys(
        [catalog["final_policy"]] + [group["policy"] for group in catalog["groups"]]
    ))
    groups = [
        "# Replace Proxy's node placeholder with an existing proxy/node group.",
        "# Merge only groups that do not already exist in your profile.",
        "[Proxy Group]",
        catalog["final_policy"] + " = select, YOUR_PROXY_NODE",
    ]
    groups += [
        policy + " = select, " + catalog["final_policy"]
        for policy in policies if policy not in ("DIRECT", "REJECT", catalog["final_policy"])
    ]
    artifacts["examples/groups.conf"] = "\n".join(groups) + "\n"

    metadata = dict(
        upstream=dict(catalog["upstream"], revision=revision),
        sources=[dict(
            path=source,
            sha256=hashlib.sha256(sources[source]).hexdigest(),
            entries=len(converted[source]),
        ) for source in sorted(sources)],
        rules=report,
    )
    artifacts["rules/manifest.json"] = json.dumps(metadata, ensure_ascii=False, indent=2) + "\n"
    return artifacts


def write_artifacts(artifacts, output):
    expected = {Path(path).name for path in artifacts if path.startswith("rules/")}
    existing = {path.name for path in (output / "rules").glob("*")}
    stale = existing - expected
    if stale:
        raise ValueError("Remove obsolete generated files explicitly: " + ", ".join(sorted(stale)))
    for relative, content in artifacts.items():
        path = output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", help="Build a specific 40-character upstream commit SHA")
    parser.add_argument("--output-dir", type=Path, default=ROOT, help="Output root (default: repository)")
    args = parser.parse_args()
    catalog = json.loads((ROOT / "catalog.json").read_text(encoding="utf-8"))
    revision = args.revision or resolve_revision(catalog["upstream"])
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("revision must be a full commit SHA")
    paths = sorted({source for group in catalog["groups"] for source in group["sources"]})
    with ThreadPoolExecutor(max_workers=8) as pool:
        data = list(pool.map(lambda source: fetch(source_url(catalog["upstream"], revision, source)), paths))
    artifacts = make_artifacts(catalog, revision, dict(zip(paths, data)))
    write_artifacts(artifacts, args.output_dir)
    manifest = json.loads(artifacts["rules/manifest.json"])
    print("{}: {} sources -> {} rule sets, {} entries".format(
        revision, len(paths), len(manifest["rules"]), sum(item["entries"] for item in manifest["rules"])
    ))


if __name__ == "__main__":
    main()
